func TestSymlinksAreNotFollowed(t *testing.T) {
	root, outside := t.TempDir(), t.TempDir()
	write(t, outside, "secret.go", "private content")
	write(t, root, "real/main.go", "package main")
	links := map[string]string{
		"escape.go": filepath.Join(outside, "secret.go"), "escape-dir": outside,
		"inside.go": "real/main.go", "inside-dir": "real", "dangling.go": "absent",
	}
	for name, target := range links {
		if err := os.Symlink(target, filepath.Join(root, name)); err != nil {
			t.Skipf("symlinks unavailable: %v", err)
		}
	}
	result, err := Scan(root, DefaultLimits())
	if err != nil || !result.Complete || len(result.Files) != 1 || result.Files[0].Path != "real/main.go" {
		t.Fatalf("symlink scan = %+v, %v", result, err)
	}
	if len(result.Skipped) != len(links) {
		t.Fatalf("symlinks not recorded: %+v", result.Skipped)
	}
	for _, skip := range result.Skipped {
		if skip.Reason != "symlink" {
			t.Errorf("unexpected reason: %+v", skip)
		}
	}
	linkRoot := filepath.Join(t.TempDir(), "root")
	if err := os.Symlink(root, linkRoot); err != nil {
		t.Fatal(err)
	}
	for _, target := range []string{linkRoot, linkRoot + string(os.PathSeparator), linkRoot + string(os.PathSeparator) + "."} {
		result, err = Scan(target, DefaultLimits())
		if err == nil || result.Complete || !strings.Contains(err.Error(), "symbolic link") {
			t.Fatalf("symlink root %q accepted: %+v, %v", target, result, err)
		}
	}
}

func TestLimitBoundaries(t *testing.T) {
	tests := []struct {
		name        string
		files       map[string]string
		configure   func(*Limits, bool)
		errContains string
	}{
		{"file bytes", map[string]string{"a.go": "1234"}, func(l *Limits, exceed bool) {
			l.MaxFileBytes = 4
			if exceed {
				l.MaxFileBytes--
			}
		}, "maximum file bytes"},
		{"total bytes", map[string]string{"a.go": "123", "b.go": "45"}, func(l *Limits, exceed bool) {
			l.MaxTotalBytes = 5
			if exceed {
				l.MaxTotalBytes--
			}
		}, "maximum total bytes"},
		{"files", map[string]string{"a.go": "1", "b.go": "2"}, func(l *Limits, exceed bool) {
			l.MaxFiles = 2
			if exceed {
				l.MaxFiles--
			}
		}, "maximum selected files"},
		{"entries", map[string]string{"a.go": "1", "other.txt": "2"}, func(l *Limits, exceed bool) {
			l.MaxEntries = 2
			if exceed {
				l.MaxEntries--
			}
		}, "maximum visited entries"},
		{"depth", map[string]string{"a/b/main.go": "1"}, func(l *Limits, exceed bool) {
			l.MaxDepth = 2
			if exceed {
				l.MaxDepth--
			}
		}, "maximum depth"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			for name, data := range tt.files {
				write(t, root, name, data)
			}
			for _, exceed := range []bool{false, true} {
				limits := DefaultLimits()
				tt.configure(&limits, exceed)
				result, err := Scan(root, limits)
				if exceed {
					if err == nil || result.Complete || !strings.Contains(err.Error(), tt.errContains) {
						t.Fatalf("expected incomplete %s failure, got %+v, %v", tt.name, result, err)
					}
				} else if err != nil || !result.Complete {
					t.Fatalf("exact limit rejected: %+v, %v", result, err)
				}
			}
		})
	}
}

