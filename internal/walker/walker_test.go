func TestLimitsMustBePositive(t *testing.T) {
	mutations := []func(*Limits){
		func(l *Limits) { l.MaxFileBytes = 0 }, func(l *Limits) { l.MaxTotalBytes = -1 },
		func(l *Limits) { l.MaxFiles = 0 }, func(l *Limits) { l.MaxEntries = 0 },
		func(l *Limits) { l.MaxDepth = 0 },
	}
	for _, mutate := range mutations {
		l := DefaultLimits()
		mutate(&l)
		result, err := Scan(t.TempDir(), l)
		if err == nil || result.Complete {
			t.Fatalf("invalid limits accepted: %+v, %v", l, err)
		}
	}
}

type failingRoot struct {
	*os.Root
	failStat string
	failOpen string
}

func (r failingRoot) Lstat(name string) (fs.FileInfo, error) {
	if name == r.failStat {
		return nil, &fs.PathError{Op: "lstat", Path: name, Err: fs.ErrPermission}
	}
	return r.Root.Lstat(name)
}

func (r failingRoot) OpenFile(name string, flags int, mode fs.FileMode) (*os.File, error) {
	if name == r.failOpen {
		return nil, &fs.PathError{Op: "open", Path: name, Err: fs.ErrPermission}
	}
	return r.Root.OpenFile(name, flags, mode)
}

func TestContextualIOFailures(t *testing.T) {
	root := t.TempDir()
	write(t, root, "a.go", "package main")
	r, err := os.OpenRoot(root)
	if err != nil {
		t.Fatal(err)
	}
	defer r.Close()
	for _, failed := range []failingRoot{
		{Root: r, failStat: "a.go"}, {Root: r, failOpen: "a.go"}, {Root: r, failOpen: "."},
	} {
		result, err := scanRoot(failed, DefaultLimits())
		if err == nil || result.Complete || !errors.Is(err, fs.ErrPermission) {
			t.Fatalf("expected contextual permission failure, got %+v, %v", result, err)
		}
		if !strings.Contains(err.Error(), "a.go") && failed.failOpen != "." {
			t.Errorf("missing path context: %v", err)
		}
	}
}
