func write(t *testing.T, root, name, content string) {
	t.Helper()
	full := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestScanRelevantFilesAndDeterministicOrder(t *testing.T) {
	root := t.TempDir()
	fixtures := map[string]string{
		"nested/main.go": "package main\n", "app.jsx": "export default null;\n",
		"go.mod": "module example.test/app\n", "go.sum": "opaque checksums\n",
		"package.json": "{malformed but inventoried}", "package-lock.json": "{}",
		"npm-shrinkwrap.json": "{}", "yarn.lock": "# locks", "pnpm-lock.yaml": "{}",
		"types.ts": "export {};", "view.tsx": "export {};", "plain.js": "let x = 1;",
		"notes.txt": "irrelevant",
	}
	for name, content := range fixtures {
		write(t, root, name, content)
	}
	wantKinds := map[string]string{
		"nested/main.go": "go_source", "app.jsx": "js_source", "go.mod": "go_module",
		"go.sum": "go_checksum", "package.json": "js_manifest", "package-lock.json": "npm_lock",
		"npm-shrinkwrap.json": "npm_lock", "yarn.lock": "yarn_lock", "pnpm-lock.yaml": "pnpm_lock",
		"types.ts": "ts_source", "view.tsx": "ts_source", "plain.js": "js_source",
	}
	first, err := Scan(root, DefaultLimits())
	if err != nil || !first.Complete {
		t.Fatalf("scan = %+v, %v", first, err)
	}
	if len(first.Files) != len(wantKinds) {
		t.Fatalf("got %d files; want %d", len(first.Files), len(wantKinds))
	}
	var bytesRead int64
	previous := ""
	for _, file := range first.Files {
		if file.Path <= previous {
			t.Errorf("file order is not strictly sorted: %q after %q", file.Path, previous)
		}
		previous = file.Path
		if file.Kind != wantKinds[file.Path] || string(file.Data) != fixtures[file.Path] || file.Size != int64(len(file.Data)) {
			t.Errorf("unexpected file: %+v", file)
		}
		bytesRead += int64(len(file.Data))
	}
	if first.BytesRead != bytesRead || first.EntriesVisited != len(fixtures)+1 {
		t.Errorf("unexpected counters: %+v", first)
	}
	second, err := Scan(root, DefaultLimits())
	if err != nil || !reflect.DeepEqual(first, second) {
		t.Fatalf("repeated scan differs: %v\n%+v\n%+v", err, first, second)
	}
}

func TestIntentionalExclusions(t *testing.T) {
	root := t.TempDir()
	for name := range ignoredDirectories {
		write(t, root, name+"/hidden.go", "package ignored")
	}
	write(t, root, "bundle.min.js", "not inspected")
	write(t, root, "auto.go", "// Code generated by generator. DO NOT EDIT.\npackage generated\n")
	write(t, root, "binary.ts", "hello\x00binary")
	write(t, root, "ordinary.go", "package ordinary\n// Code generated too late. DO NOT EDIT.\n")
	write(t, root, "near.go", "// Code generated without a standard marker\npackage ordinary\n")
	result, err := Scan(root, DefaultLimits())
	if err != nil || !result.Complete {
		t.Fatalf("scan = %+v, %v", result, err)
	}
	if len(result.Files) != 2 || result.Files[0].Path != "near.go" || result.Files[1].Path != "ordinary.go" {
		t.Errorf("unexpected included files: %+v", result.Files)
	}
	if len(result.Skipped) != len(ignoredDirectories)+3 {
		t.Fatalf("unexpected exclusions: %+v", result.Skipped)
	}
	got := map[string]string{}
	for _, skip := range result.Skipped {
		got[skip.Path] = skip.Reason
	}
	for name := range ignoredDirectories {
		if got[name] != "ignored_directory" {
			t.Errorf("%s exclusion = %q", name, got[name])
		}
	}
	if got["bundle.min.js"] != "generated" || got["auto.go"] != "generated" || got["binary.ts"] != "binary" {
		t.Errorf("unexpected exclusion reasons: %+v", got)
	}
}

func TestGeneratedGoHeaderGrammar(t *testing.T) {
	const marker = "// Code generated by a generator. DO NOT EDIT."
	tests := []struct {
		name string
		data string
		want bool
	}{
		{"proper header", marker + "\npackage main\n", true},
		{"header and package tab", marker + "\npackage\tmain\n", true},
		{"header after comments", "/* license */\n\n" + marker + "\npackage main", true},
		{"marker line inside leading block comment", "/*\n" + marker + "\n*/\npackage main", true},
		{"CRLF header", marker + "\r\npackage main\r\n", true},
		{"empty generator", "// Code generated  DO NOT EDIT.\npackage main", true},
		{"marker after package", "package main\n\n" + marker + "\nfunc main() {}\n", false},
		{"marker after package tab", "package\tmain\n\n" + marker + "\nfunc main() {}\n", false},
		{"marker after package newline", "package\nmain\n\n" + marker, false},
		{"marker after noncomment text", "var x = 1\n" + marker, false},
		{"marker in raw string", "package main\nvar x = `\n" + marker + "\n`", false},
		{"marker after malformed token", "@\n" + marker, false},
		{"indented marker", "\t" + marker + "\npackage main", false},
		{"marker suffix with trailing text", marker + " extra\npackage main", false},
		{"marker missing generator spacing", "// Code generated DO NOT EDIT.\npackage main", false},
		{"empty file", "", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			write(t, root, "input.go", tt.data)
			result, err := Scan(root, DefaultLimits())
			if err != nil || !result.Complete {
				t.Fatalf("scan = %+v, %v", result, err)
			}
			if got := len(result.Skipped) == 1 && result.Skipped[0].Reason == "generated"; got != tt.want {
				t.Fatalf("generated = %t; want %t (result: %+v)", got, tt.want, result)
			}
			if !tt.want && (len(result.Files) != 1 || string(result.Files[0].Data) != tt.data) {
				t.Fatalf("nongenerated contents excluded or changed: %+v", result)
			}
		})
	}
}

