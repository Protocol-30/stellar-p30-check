func TestYarnClassicSelectors(t *testing.T) {
	file := walker.File{Path: "yarn.lock", Data: []byte(`# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

"@stellar/stellar-sdk@^17.3.0", "@stellar/stellar-sdk@~17.3.0":
  version "17.3.0"
  resolved "https://registry.yarnpkg.com/@stellar/stellar-sdk/-/stellar-sdk-17.3.0.tgz#123"
  integrity sha512-example
  dependencies:
    "@stellar/js-xdr" "^3.0.0"

"@stellar/stellar-sdk@16.4.0":
  version "16.4.0"
  resolved "https://registry.yarnpkg.com/@stellar/stellar-sdk/-/stellar-sdk-16.4.0.tgz#456"
`)}
	lock, err := parseYarnLock(file)
	if err != nil || lock.Unsupported != "" {
		t.Fatalf("parse: %+v %v", lock, err)
	}
	for _, tc := range []struct{ declared, version string }{{"^17.3.0", "17.3.0"}, {"~17.3.0", "17.3.0"}, {"16.4.0", "16.4.0"}} {
		got, ok := lock.Resolve(".", "@stellar/stellar-sdk", tc.declared)
		if !ok || got.Version != tc.version || got.Specifier != tc.declared || !strings.HasPrefix(got.Resolved, "https://registry.yarnpkg.com/") || len(got.Reasons) != 0 {
			t.Fatalf("resolve %q: %+v found=%v", tc.declared, got, ok)
		}
	}
	if _, ok := lock.Resolve(".", "@stellar/stellar-sdk", "^16.4.0"); ok {
		t.Fatal("selector without exact declaration match was guessed")
	}
	if _, ok := lock.Resolve(".", "@stellar/js-xdr", "^3.0.0"); ok {
		t.Fatal("nested dependency was interpreted as a direct lock record")
	}
	if _, ok := lock.Resolve("packages/app", "@stellar/stellar-sdk", "^17.3.0"); ok {
		t.Fatal("descendant workspace membership was inferred from a selector-only lock")
	}
}

func TestYarnScopeAndMissingVersion(t *testing.T) {
	lock, err := parseYarnLock(walker.File{Path: "app/yarn.lock", Data: []byte("# yarn lockfile v1\npackage@1.0.0:\n  resolved https://registry.yarnpkg.com/package/-/package-1.0.0.tgz\n")})
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := lock.Resolve("other", "package", "1.0.0"); ok {
		t.Fatal("lock escaped its package scope")
	}
	got, ok := lock.Resolve("app", "package", "1.0.0")
	if !ok || len(got.Reasons) == 0 {
		t.Fatalf("missing version was not uncertain: %+v found=%v", got, ok)
	}
}

func TestYarnRejectsMalformedAndUnsupported(t *testing.T) {
	for _, tc := range []struct {
		name, data  string
		unsupported bool
	}{
		{"modern", "__metadata:\n  version: 8\n", true},
		{"spoofed-header-modern", "# yarn lockfile v1\n__metadata:\n  version: 8\n", true},
		{"missing-header", "package@1.0.0:\n  version \"1.0.0\"\n", true},
		{"duplicate-selector", "# yarn lockfile v1\na@1.0.0:\n  version 1.0.0\na@1.0.0:\n  version 1.0.0\n", false},
		{"duplicate-version", "# yarn lockfile v1\na@1.0.0:\n  version 1.0.0\n  version 2.0.0\n", false},
		{"unterminated-selector", "# yarn lockfile v1\n\"a@1.0.0:\n  version 1.0.0\n", false},
		{"field-before-selector", "# yarn lockfile v1\n  version 1.0.0\n", false},
		{"bad-record", "# yarn lockfile v1\na@1.0.0\n  version 1.0.0\n", false},
		{"bad-version", "# yarn lockfile v1\na@1.0.0:\n  version \"bad\n", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			lock, err := parseYarnLock(walker.File{Path: "yarn.lock", Data: []byte(tc.data)})
			if tc.unsupported {
				if err != nil || lock.Unsupported == "" {
					t.Fatalf("expected unsupported: %+v %v", lock, err)
				}
			} else if err == nil || !strings.Contains(err.Error(), "yarn.lock") {
				t.Fatalf("expected contextual error: %+v %v", lock, err)
			}
		})
	}
}

const pnpmFixture = `lockfileVersion: '9.0'
settings:
  autoInstallPeers: true
importers:
  .:
    dependencies:
      '@stellar/stellar-sdk':
        specifier: ^17.3.0
        version: 17.3.0
  packages/old:
    dependencies:
      '@stellar/stellar-sdk':
        specifier: 16.4.0
        version: 16.4.0
packages:
  '@stellar/stellar-sdk@17.3.0':
    resolution:
      integrity: sha512-example
      tarball: https://registry.npmjs.org/@stellar/stellar-sdk/-/stellar-sdk-17.3.0.tgz
  '@stellar/stellar-sdk@16.4.0':
    resolution: {integrity: sha512-example}
snapshots: {}
`

func TestPNPMImporterResolution(t *testing.T) {
	lock, err := parsePNPMLock(walker.File{Path: "pnpm-lock.yaml", Data: []byte(pnpmFixture)})
	if err != nil || lock.Unsupported != "" {
		t.Fatalf("parse: %+v %v", lock, err)
	}
	got, ok := lock.Resolve(".", "@stellar/stellar-sdk", "^17.3.0")
	if !ok || got.Version != "17.3.0" || got.Specifier != "^17.3.0" || got.Resolved == "" || len(got.Reasons) != 0 {
		t.Fatalf("root: %+v found=%v", got, ok)
	}
	got, ok = lock.Resolve("packages/old", "@stellar/stellar-sdk", "16.4.0")
	if !ok || got.Version != "16.4.0" || got.Resolved != "" || len(got.Reasons) == 0 {
		t.Fatalf("integrity-only origin was trusted: %+v found=%v", got, ok)
	}
	if _, ok := lock.Resolve("packages/absent", "@stellar/stellar-sdk", "^17.3.0"); ok {
		t.Fatal("missing importer was guessed")
	}
	got, ok = lock.Resolve(".", "@stellar/stellar-sdk", "17.3.0")
	if !ok || len(got.Reasons) == 0 {
		t.Fatalf("specifier mismatch not uncertain: %+v found=%v", got, ok)
	}
}

func TestPNPMNestedLockScope(t *testing.T) {
	lock, err := parsePNPMLock(walker.File{Path: "monorepo/pnpm-lock.yaml", Data: []byte(pnpmFixture)})
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := lock.Resolve("monorepo/packages/old", "@stellar/stellar-sdk", "16.4.0"); !ok {
		t.Fatal("nested importer not selected")
	}
	if _, ok := lock.Resolve("other", "@stellar/stellar-sdk", "^17.3.0"); ok {
		t.Fatal("lock escaped scope")
	}
}

func TestPNPMUnknownPackageAndPeerQualifier(t *testing.T) {
	input := strings.Replace(pnpmFixture, "version: 17.3.0", "version: 17.3.0(peer@1.0.0)", 1)
	lock, err := parsePNPMLock(walker.File{Path: "pnpm-lock.yaml", Data: []byte(input)})
	if err != nil {
		t.Fatal(err)
	}
	got, ok := lock.Resolve(".", "@stellar/stellar-sdk", "^17.3.0")
	if !ok || got.Version != "17.3.0" || len(got.Reasons) == 0 {
		t.Fatalf("peer qualifier not explicit: %+v found=%v", got, ok)
	}
	input = strings.Replace(pnpmFixture, "version: 17.3.0", "version: 17.4.0", 1)
	lock, err = parsePNPMLock(walker.File{Path: "pnpm-lock.yaml", Data: []byte(input)})
	if err != nil {
		t.Fatal(err)
	}
	got, ok = lock.Resolve(".", "@stellar/stellar-sdk", "^17.3.0")
	if !ok || got.Resolved != "" || len(got.Reasons) == 0 {
		t.Fatalf("missing package not uncertain: %+v found=%v", got, ok)
	}
}

func TestPNPMRejectsUnsafeOrMalformedYAML(t *testing.T) {
	for _, tc := range []struct {
		name, data  string
		unsupported bool
	}{
		{"v6", "lockfileVersion: '6.0'\nimporters: {}\n", true},
		{"unknown-version", "importers: {}\n", true},
		{"bad-yaml", "lockfileVersion: [\n", false},
		{"alias", "lockfileVersion: '9.0'\nimporters: &i {}\npackages: *i\n", false},
		{"duplicate", "lockfileVersion: '9.0'\nlockfileVersion: '6.0'\nimporters: {}\n", false},
		{"complex-key", "lockfileVersion: '9.0'\nimporters:\n  ? [a,b]\n  : {}\n", false},
		{"multiple-documents", "lockfileVersion: '9.0'\nimporters: {}\n---\nmore: true\n", false},
		{"root-scalar", "9.0", false},
		{"missing-importers", "lockfileVersion: '9.0'\n", false},
		{"bad-dependencies", "lockfileVersion: '9.0'\nimporters:\n  .:\n    dependencies: []\n", false},
		{"bad-record", "lockfileVersion: '9.0'\nimporters:\n  .:\n    dependencies:\n      sdk: {specifier: 1.0.0}\n", false},
		{"bad-tarball", "lockfileVersion: '9.0'\nimporters: {}\npackages:\n  'sdk@1.0.0':\n    resolution: {tarball: []}\n", false},
		{"depth", "lockfileVersion: '9.0'\nimporters: {}\nextra: " + strings.Repeat("[", 70) + strings.Repeat("]", 70) + "\n", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			lock, err := parsePNPMLock(walker.File{Path: "pnpm-lock.yaml", Data: []byte(tc.data)})
			if tc.unsupported {
				if err != nil || lock.Unsupported == "" {
					t.Fatalf("expected unsupported: %+v %v", lock, err)
				}
			} else if err == nil || !strings.Contains(err.Error(), "pnpm-lock.yaml") {
				t.Fatalf("expected contextual error: %+v %v", lock, err)
			}
		})
	}
}
